import { chromium } from '@playwright/test'
import fs from 'node:fs/promises'
const directory=new URL('../docs/demo/',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1')
await fs.mkdir(directory,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:directory,size:{width:1440,height:1000}}})
const page=await context.newPage()
await page.goto(process.env.COMMITGYM_TEST_URL||'http://127.0.0.1:5173')
async function caption(text){await page.evaluate(text=>{let el=document.getElementById('recording-caption');if(!el){el=document.createElement('div');el.id='recording-caption';el.style.cssText='position:fixed;bottom:18px;left:270px;right:30px;padding:16px 22px;background:#111d0ef5;color:#d9f2c3;border:1px solid #79975d;border-radius:8px;z-index:1000;font:16px Segoe UI;box-shadow:0 4px 30px #0008;pointer-events:none';document.body.appendChild(el)}el.textContent=text},text)}
await caption('CommitGym: train agents to recover safely. This recording uses the real local simulator and backend.')
await page.waitForTimeout(4500)
await page.getByRole('button',{name:'Start episode',exact:true}).click()
for(let i=0;i<3;i++)await page.getByRole('button',{name:'Step',exact:true}).click()
await caption('The deployment changed the candidate release, but returned a timeout. A retry could duplicate an already committed operation.')
await page.waitForTimeout(6500)
await page.getByRole('button',{name:'Step',exact:true}).click()
await caption('Inspection reconciles the actual state. Tool responses and infrastructure truth are deliberately separate.')
await page.waitForTimeout(4500)
await page.getByRole('button',{name:'Run episode',exact:true}).click()
await page.locator('.run-metrics').getByText('Deployed v2 · verified',{exact:true}).waitFor()
await caption('The baseline drains traffic, migrates, probes and verifies. The independent judge accepts the result: v2 deployed and verified.')
await page.waitForTimeout(5000)
await page.getByLabel('FAILURE SCENARIO').selectOption('stale_health')
await page.getByRole('button',{name:'New episode',exact:true}).click()
await page.getByRole('button',{name:'Run episode',exact:true}).click()
await page.locator('.run-metrics').getByText('Safe rollback · v1 restored',{exact:true}).waitFor()
await page.locator('.event').filter({hasText:'Cached healthy result'}).click()
await page.evaluate(()=>window.scrollTo(0,230))
await caption('A cached healthy result is not fresh evidence. Here the judge accepts a safe rollback: v1 restored. That is labelled as a rollback, not a deployment.')
await page.waitForTimeout(6500)
await page.evaluate(()=>window.scrollTo(0,0))
await page.getByLabel('FAILURE SCENARIO').selectOption('partial_success')
await page.getByLabel('AGENT POLICY').selectOption('mock_tools')
await caption('Nebius access is pending, so this is the offline mock tool adapter, NOT an LLM. A local planner emits tool calls through the same validation and three-operation batches Nemotron uses. Zero tokens.')
await page.getByRole('button',{name:'New episode',exact:true}).click()
await page.getByRole('button',{name:'Run episode',exact:true}).click()
await page.locator('.run-metrics').getByText('Deployed v2 · verified',{exact:true}).waitFor()
await page.waitForTimeout(8000)
await page.getByRole('navigation').getByRole('button',{name:'Training',exact:true}).click()
await page.evaluate(()=>window.scrollTo(0,0))
await caption('Real PPO training: 300,032 timesteps. The curve records measured rewards, including curriculum resets early in training.')
await page.waitForTimeout(6500)
await page.getByRole('navigation').getByRole('button',{name:'Evaluations',exact:true}).click()
await caption('Both local policies recover safely. PPO always rolls back; the baseline completes more upgrades. Higher reward is not superior deployment performance.')
await page.waitForTimeout(6500)
await page.getByRole('navigation').getByRole('button',{name:'Settings',exact:true}).click()
await caption('NVIDIA Nemotron tool integration is implemented, but live Nebius authentication and inference remain unverified. No live outputs are fabricated.')
await page.waitForTimeout(6500)
await page.getByRole('navigation').getByRole('button',{name:'History',exact:true}).click()
await page.getByRole('button',{name:/Inspect episode/}).first().click()
await page.getByRole('button',{name:'Verify replay',exact:true}).click()
await caption('Every state, action, reward and invariant is persisted. Replay recomputes the episode from its original seed and actions.')
await page.waitForTimeout(5000)
await page.getByRole('navigation').getByRole('button',{name:'Overview',exact:true}).click()
await page.evaluate(()=>window.scrollTo(0,0))
await caption('CommitGym · A working recovery workbench. Live Nemotron inference and public deployment are pending; this is actual local execution.')
await page.waitForTimeout(4000)
const video=page.video()
await context.close()
await video.saveAs(directory+'/commitgym-local-demo.webm')
const original=await video.path();if(original!==directory+'/commitgym-local-demo.webm')await fs.unlink(original)
await browser.close()
console.log('Saved local simulator demonstration; live inference remains unverified.')
